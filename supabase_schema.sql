-- 1. Forum Posts Table
CREATE TABLE IF NOT EXISTS public.forum_posts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    content TEXT NOT NULL,
    author TEXT NOT NULL DEFAULT 'Candidate',
    author_role TEXT DEFAULT 'Engineering Student',
    category TEXT DEFAULT 'Placements',
    upvotes INT DEFAULT 1,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Forum Comments Table
CREATE TABLE IF NOT EXISTS public.forum_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id BIGINT REFERENCES public.forum_posts(id) ON DELETE CASCADE,
    author TEXT NOT NULL DEFAULT 'Peer',
    content TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. AI Mock Interview Records Table
CREATE TABLE IF NOT EXISTS public.mock_interviews (
    id TEXT PRIMARY KEY,
    role TEXT NOT NULL,
    difficulty TEXT NOT NULL,
    overall_score INT,
    technical_score INT,
    communication_score INT,
    confidence_score INT,
    hiring_decision TEXT,
    evaluation JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Generated Study Plans Table
CREATE TABLE IF NOT EXISTS public.study_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject TEXT NOT NULL,
    duration_days INT,
    hours_per_day INT,
    target_goal TEXT,
    difficulty TEXT,
    plan_data JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. User Resumes Table
CREATE TABLE IF NOT EXISTS public.user_resumes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT,
    phone TEXT,
    linkedin TEXT,
    github TEXT,
    summary TEXT,
    skills JSONB,
    education JSONB,
    projects JSONB,
    experiences JSONB,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- =========================================================================
-- ROW LEVEL SECURITY (RLS) POLICIES
-- Allows reads and inserts from your Next.js application
-- =========================================================================

ALTER TABLE public.forum_posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.forum_comments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mock_interviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_plans ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_resumes ENABLE ROW LEVEL SECURITY;

-- Allow public read access
CREATE POLICY "Allow public read forum_posts" ON public.forum_posts FOR SELECT USING (true);
CREATE POLICY "Allow public insert forum_posts" ON public.forum_posts FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update forum_posts" ON public.forum_posts FOR UPDATE USING (true);

CREATE POLICY "Allow public read forum_comments" ON public.forum_comments FOR SELECT USING (true);
CREATE POLICY "Allow public insert forum_comments" ON public.forum_comments FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public all mock_interviews" ON public.mock_interviews FOR ALL USING (true);
CREATE POLICY "Allow public all study_plans" ON public.study_plans FOR ALL USING (true);
CREATE POLICY "Allow public all user_resumes" ON public.user_resumes FOR ALL USING (true);

